def slugify(cat: str) -> str:
    return re.sub(r"[^a-z0-9]+", "-", cat.lower()).strip("-")


def fetch_inner(name: str) -> str:
    url = f"https://api.iconify.design/lucide/{name}.svg"
    # 파이썬 기본 User-Agent 는 403 으로 막힌다(2026-11-27 실측) → 일반 이름을 단다
    req = urllib.request.Request(url, headers={"User-Agent": "icon-sprite-builder/1.0"})
    with urllib.request.urlopen(req, timeout=20) as r:
        svg = r.read().decode("utf-8")
    m = re.search(r"<svg[^>]*>(.*)</svg>", svg, re.S)
    if not m or "viewBox=\"0 0 24 24\"" not in svg:
        raise SystemExit(f"예상 밖 SVG 형식: {name}")
    return m.group(1).strip()


def main() -> None:
    cache: dict[str, str] = {}
    symbols = []
    for sid, name in UI_ICONS.items():
        cache.setdefault(name, fetch_inner(name))
        symbols.append(f'  <symbol id="i-{sid}" viewBox="0 0 24 24">{cache[name]}</symbol>')
    for cat, name in CAT_ICONS.items():
        cache.setdefault(name, fetch_inner(name))
        symbols.append(f'  <symbol id="cat-{slugify(cat)}" viewBox="0 0 24 24">{cache[name]}</symbol>')
    body = "\n".join(symbols)
    OUT.write_text(
        f'<svg xmlns="http://www.w3.org/2000/svg">\n{NOTICE}\n{body}\n</svg>\n', encoding="utf-8"
    )
    print(f"icons.svg: 공통 {len(UI_ICONS)} + 카테고리 {len(CAT_ICONS)} = {len(symbols)}개, "
          f"{OUT.stat().st_size // 1024}KB")


if __name__ == "__main__":
    main()
